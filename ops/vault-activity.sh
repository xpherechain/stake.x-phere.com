#!/usr/bin/env bash
# ============================================================
# 볼트 활동 감시. cron 에서 5분마다 호출한다.
#
#   ./vault-activity.sh              새 블록 스캔 + 건별 슬랙 알림
#   ./vault-activity.sh --quiet      알림 없이 스캔만 (백필용)
#   ./vault-activity.sh --from-days=3     state/ 를 잃었을 때 3일치 재앵커
#   ./vault-activity.sh --from-block=N    블록 번호로 재앵커
#
# 알리는 것: 예치 · 언스테이크 요청 · 언스테이크 수령 · 보상 수령.
#
# 읽기 전용이다. 개인키를 쓰지 않으므로 정산 파이프라인과 완전히 분리돼 있고,
# 여기가 죽어도 정산·소각에는 영향이 없다.
#
# 2026-08-12~25 예치왕 이벤트용으로 만들었고 데일리 리포트/최종 스냅샷도 있었으나
# 이벤트 종료와 함께 제거했다. 남은 활동 알림은 상시 운영 대상이다.
# ============================================================
set -euo pipefail
cd "$(dirname "$0")"
set -a; source ./.env; set +a

exec python3 ./vault-activity.py watch "$@"
